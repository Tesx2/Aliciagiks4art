document.addEventListener('DOMContentLoaded', () => {
  const gallery = document.getElementById('gallery');
  const lightbox = document.getElementById('lightbox');
  const lbImage = document.getElementById('lightboxImage');
  const lbTitle = document.getElementById('lightboxTitle');
  const lbDesc = document.getElementById('lightboxDesc');
  const lbClose = document.querySelector('.lightbox-close');
  const themeToggle = document.getElementById('themeToggle');

  // Theme setup
  function applyTheme(theme){
    document.documentElement.setAttribute('data-theme', theme);
    if(themeToggle) themeToggle.setAttribute('aria-pressed', theme === 'light' ? 'true' : 'false');
    localStorage.setItem('site-theme', theme);
  }
  const savedTheme = localStorage.getItem('site-theme') || 'dark';
  applyTheme(savedTheme);
  if(themeToggle){
    themeToggle.addEventListener('click', () => {
      const next = document.documentElement.getAttribute('data-theme') === 'light' ? 'dark' : 'light';
      applyTheme(next);
    });
  }

  const nav = document.querySelector('.nav');
  const menuToggle = document.querySelector('.menu-toggle');
  const navLinks = document.querySelectorAll('.nav-links a');
  const lbVideo = document.getElementById('lightboxVideo');
  let currentGalleryItems = [];
  let currentLightboxIndex = -1;

  function setMenuState(isOpen) {
    if (!nav || !menuToggle) return;
    nav.classList.toggle('is-open', isOpen);
    menuToggle.setAttribute('aria-expanded', String(isOpen));
    document.body.classList.toggle('menu-open', isOpen);
  }

  if (menuToggle) {
    menuToggle.addEventListener('click', () => {
      const isOpen = nav && nav.classList.contains('is-open');
      setMenuState(!isOpen);
    });
  }

  navLinks.forEach((link) => {
    link.addEventListener('click', () => setMenuState(false));
  });

  document.addEventListener('click', (event) => {
    if (!nav || !nav.classList.contains('is-open')) return;
    if (!nav.contains(event.target)) {
      setMenuState(false);
    }
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && nav && nav.classList.contains('is-open')) {
      setMenuState(false);
      menuToggle?.focus();
    }
  });

  function openLightboxItem(item, index){
    // Close or reset any previous media
    try{ if(lbVideo){ lbVideo.pause(); lbVideo.src = ''; lbVideo.hidden = true; } }catch(e){}
    try{ if(lbImage){ lbImage.src = ''; lbImage.hidden = true; } }catch(e){}

    lbTitle.textContent = item.title || '';
    lbDesc.textContent = item.desc || '';

    if(item.type === 'video'){
      // show video player
      if(lbVideo){
        lbVideo.src = item.src;
        if(item.poster) lbVideo.setAttribute('poster', item.poster); else lbVideo.removeAttribute('poster');
        lbVideo.hidden = false;
        lbVideo.controls = true;
        lbVideo.muted = true; // start muted to avoid unexpected sound (user can unmute)
        lbVideo.playsInline = true;
      }
    }else{
      // show image
      if(lbImage){
        lbImage.src = item.src;
        lbImage.alt = item.alt || item.title || '';
        lbImage.hidden = false;
      }
    }

    lightbox.setAttribute('aria-hidden','false');
    document.body.style.overflow = 'hidden';
    currentLightboxIndex = index;
    if(lbClose) lbClose.focus();
  }

  function openLightboxByIndex(idx){
    if(!Array.isArray(currentGalleryItems) || idx < 0 || idx >= currentGalleryItems.length) return;
    const item = currentGalleryItems[idx];
    openLightboxItem(item, idx);
  }

  // Load gallery manifest (generated by scripts/generate-manifest.js)
  async function loadManifestAndBuild(){
    try{
      const resp = await fetch('geeks4drisony/manifest.json', { cache: 'no-store' });
      if(!resp.ok) throw new Error('Manifest not found');
      const manifest = await resp.json();
      const categories = manifest.categories || [];
      // Build a flat list of all items with category attached
      const allItems = [];
      categories.forEach(cat => {
        cat.items.forEach(it => allItems.push(Object.assign({ category: cat.name }, it)));
      });

      // Determine featured (most recent by mtimeMs)
      let featuredItem = null;
      if(allItems.length){
        featuredItem = allItems.reduce((a,b) => ( (a.mtimeMs || 0) > (b.mtimeMs || 0) ? a : b ));
      }

      // Build category filter buttons
      const filtersEl = document.getElementById('categoryFilters');
      if(filtersEl){
        const allBtn = document.createElement('button');
        allBtn.type = 'button';
        allBtn.className = 'filter-btn active';
        allBtn.dataset.category = 'All';
        allBtn.textContent = 'All';
        filtersEl.appendChild(allBtn);

        const featBtn = document.createElement('button');
        featBtn.type = 'button';
        featBtn.className = 'filter-btn';
        featBtn.dataset.category = 'Featured';
        featBtn.textContent = 'Featured';
        filtersEl.appendChild(featBtn);

        categories.forEach(cat => {
          const btn = document.createElement('button');
          btn.type = 'button';
          btn.className = 'filter-btn';
          btn.dataset.category = cat.name;
          btn.textContent = cat.name;
          filtersEl.appendChild(btn);
        });

        filtersEl.addEventListener('click', (ev) => {
          const t = ev.target.closest('button');
          if(!t) return;
          Array.from(filtersEl.querySelectorAll('button')).forEach(b=>b.classList.remove('active'));
          t.classList.add('active');
          const cat = t.dataset.category;
          filterGallery(cat, { allItems, featuredItem, categories });
        });
      }

      // Render all projects by default
      gallery.classList.remove('featured-gallery');
      renderGallery(allItems);

    }catch(err){
      console.warn('Could not load manifest:', err);
      if (gallery) {
        gallery.innerHTML = '<p class="gallery-empty">Projects could not load. Open this site through a local server (not as a file) so the gallery can read the project manifest.</p>';
      }
    }
  }

  function createCard(item, index){
    const article = document.createElement('article');
    article.className = 'card';
    article.setAttribute('role', 'button');
    article.setAttribute('tabindex', '0');
    article.setAttribute('aria-label', `View ${item.title || 'project'}${item.category ? ` — ${item.category}` : ''}`);
    article.dataset.title = item.title || '';
    article.dataset.desc = item.desc || '';
    article.dataset.src = item.src;
    article.dataset.category = item.category || '';
    article.dataset.type = item.type || 'image';
    article.dataset.index = String(index);

    const figure = document.createElement('figure');

    if (item.category) {
      const tag = document.createElement('span');
      tag.className = 'card-category';
      tag.textContent = item.category;
      figure.appendChild(tag);
    }

    if(item.type === 'video'){
      const vid = document.createElement('video');
      vid.src = item.src;
      if(item.poster) vid.setAttribute('poster', item.poster);
      vid.setAttribute('playsinline', '');
      vid.setAttribute('muted', '');
      vid.setAttribute('preload', 'metadata');
      vid.setAttribute('aria-hidden', 'true');
      figure.appendChild(vid);

      const badge = document.createElement('span');
      badge.className = 'video-badge';
      badge.innerHTML = '<svg width="14" height="14" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden="true"><path d="M8 5v14l11-7L8 5z" fill="currentColor"/></svg><span>Motion</span>';
      figure.appendChild(badge);
    } else {
      const img = document.createElement('img');
      img.src = item.src;
      img.alt = item.alt || item.title || '';
      img.loading = 'lazy';
      img.decoding = 'async';
      figure.appendChild(img);
    }

    const figcap = document.createElement('figcaption');
    figcap.className = 'overlay';
    figcap.innerHTML = `<div class="overlay-inner"><h3>${item.title || ''}</h3></div>`;
    figure.appendChild(figcap);

    const cap = document.createElement('div');
    cap.className = 'card-caption';
    cap.textContent = item.title || item.filename || '';
    figure.appendChild(cap);

    article.appendChild(figure);
    return article;
  }

  function renderGallery(items){
    // items: array of media objects
    currentGalleryItems = items || [];
    gallery.innerHTML = '';
    const frag = document.createDocumentFragment();
    currentGalleryItems.forEach((it, idx) => frag.appendChild(createCard(it, idx)));
    gallery.appendChild(frag);
  }

  function filterGallery(category, ctx){
    // ctx = { allItems, featuredItem, categories }
    if(category === 'All'){
      gallery.classList.remove('featured-gallery');
      renderGallery(ctx?.allItems || []);
      return;
    }
    if(category === 'Featured'){
      if(ctx && ctx.featuredItem){
        gallery.classList.add('featured-gallery');
        renderGallery([ctx.featuredItem]);
      } else {
        gallery.classList.remove('featured-gallery');
        renderGallery([]);
      }
      return;
    }
    // remove featured layout for category views
    gallery.classList.remove('featured-gallery');
    // find items for the selected category
    if(ctx && ctx.allItems){
      const items = ctx.allItems.filter(it => it.category === category);
      renderGallery(items);
      return;
    }
    // fallback: filter existing DOM nodes
    Array.from(gallery.children).forEach(c => {
      const cat = c.dataset.category || '';
      c.style.display = (cat === category) ? '' : 'none';
    });
  }

  // Delegated click handler for gallery cards (open lightbox)
  gallery && gallery.addEventListener('click', (ev) => {
    const card = ev.target.closest('.card');
    if(!card) return;
    const idx = parseInt(card.dataset.index || '-1', 10);
    if(!isNaN(idx) && idx >= 0){
      openLightboxByIndex(idx);
    }
  });

  gallery && gallery.addEventListener('keydown', (ev) => {
    if (ev.key !== 'Enter' && ev.key !== ' ') return;
    const card = ev.target.closest('.card');
    if (!card) return;
    ev.preventDefault();
    const idx = parseInt(card.dataset.index || '-1', 10);
    if (!isNaN(idx) && idx >= 0) openLightboxByIndex(idx);
  });

  // Scroll reveal for section entrances
  const revealEls = document.querySelectorAll('.reveal');
  if (revealEls.length && 'IntersectionObserver' in window) {
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      });
    }, { threshold: 0.12, rootMargin: '0px 0px -8% 0px' });

    revealEls.forEach((el) => revealObserver.observe(el));
  } else {
    revealEls.forEach((el) => el.classList.add('is-visible'));
  }

  // Lightbox controls: close, backdrop click, esc
  lbClose && lbClose.addEventListener('click', ()=>{
    lightbox.setAttribute('aria-hidden','true');
    document.body.style.overflow = '';
    // pause and reset video if present
    try{ if(lbVideo){ lbVideo.pause(); lbVideo.currentTime = 0; lbVideo.src = ''; lbVideo.hidden = true; } }catch(e){}
    try{ if(lbImage){ lbImage.src = ''; lbImage.hidden = true; } }catch(e){}
    currentLightboxIndex = -1;
  });
  lightbox && lightbox.addEventListener('click', (ev)=>{
    if(ev.target === lightbox) {
      lbClose && lbClose.click();
    }
  });
  document.addEventListener('keydown', (ev)=>{
    if(ev.key === 'Escape' && lightbox.getAttribute('aria-hidden') === 'false'){
      lbClose && lbClose.click();
      return;
    }
    // left/right navigation when lightbox open
    if(lightbox.getAttribute('aria-hidden') === 'false'){
      if(ev.key === 'ArrowLeft'){
        if(currentLightboxIndex > 0) openLightboxByIndex(currentLightboxIndex - 1);
      } else if(ev.key === 'ArrowRight'){
        if(currentLightboxIndex < currentGalleryItems.length - 1) openLightboxByIndex(currentLightboxIndex + 1);
      }
    }
  });

  // Kick off manifest load
  loadManifestAndBuild();


});
